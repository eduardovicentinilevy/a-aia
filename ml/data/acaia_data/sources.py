def convert_oasst(rows: list[dict], lang: str = "pt-BR") -> list[list[dict]]:
    """OpenAssistant stores conversation TREES. From each pt-BR root we follow the best-ranked
    reply at every step (rank 0 = preferred by reviewers) and keep conversations ending in an
    assistant message."""
    children: dict[str, list[dict]] = defaultdict(list)
    roots: list[dict] = []
    for row in rows:
        if row.get("deleted") or row.get("review_result") is False:
            continue
        if row.get("parent_id") is None:
            if row.get("lang") == lang and row.get("role") == "prompter":
                roots.append(row)
        else:
            children[row["parent_id"]].append(row)

    def best(options: list[dict]) -> dict | None:
        ranked = sorted(options, key=lambda r: (r.get("rank") is None, r.get("rank") or 0))
        return ranked[0] if ranked else None

    conversations: list[list[dict]] = []
    for root in roots:
        messages, node = [], root
        while node is not None:
            messages.append({"role": "user" if node["role"] == "prompter" else "assistant", "content": node["text"].strip()})
            node = best(children.get(node["message_id"], []))
        while messages and messages[-1]["role"] != "assistant":
            messages.pop()
        if len(messages) >= 2:
            conversations.append(messages)
    return conversations


def convert_aya(rows: list[dict], language_code: str = "por") -> list[list[dict]]:
    conversations = []
    for row in rows:
        if row.get("language_code") != language_code:
            continue
        question, answer = (row.get("inputs") or "").strip(), (row.get("targets") or "").strip()
        if question and answer:
            conversations.append([{"role": "user", "content": question}, {"role": "assistant", "content": answer}])
    return conversations


CONVERTERS = {"oasst2": convert_oasst, "aya": convert_aya}
